function makeCurve(base: number, peakMult: number, noiseSeed: number, spikeAt?: number): number[] {
  return Array.from({ length: 24 }, (_, h) => {
    const daylight = h >= 7 && h <= 19 ? Math.sin(((h - 7) / 12) * Math.PI) : 0.08;
    const wave = 1 + daylight * (peakMult - 1) + Math.sin(h * 1.3 + noiseSeed) * 0.06;
    const spike = spikeAt === h ? 1.55 : 1;
    return Number((base * wave * spike).toFixed(1));
  });
}

